-- Save the intro flag without granting clients permission to edit XP.
create or replace function public.complete_filler_intro()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_user_id uuid := auth.uid();
begin
    if v_user_id is null then raise exception 'Not authenticated'; end if;
    insert into public.player_progress (user_id, intro_completed, updated_at)
    values (v_user_id, true, now())
    on conflict (user_id) do update
        set intro_completed = true, updated_at = now();
    return jsonb_build_object('success', true);
end;
$$;
revoke all on function public.complete_filler_intro() from public;
revoke all on function public.complete_filler_intro() from anon;
grant execute on function public.complete_filler_intro() to authenticated;

-- Atomically save completion, stars, best result and one-time XP.
create or replace function public.complete_campaign_level_with_stars(
    p_level_id integer,
    p_moves integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_user_id uuid := auth.uid();
    v_max_moves integer;
    v_stars integer;
    v_base_score integer;
    v_score integer;
    v_first_completion boolean;
    v_xp integer;
    v_best_stars integer;
    v_xp_awarded integer;
begin
    if v_user_id is null then
        raise exception 'Not authenticated';
    end if;
    if p_level_id is null or p_level_id < 1 or p_level_id > 10 then
        raise exception 'Invalid level id';
    end if;
    if p_moves is null or p_moves < 1 then
        raise exception 'Invalid move count';
    end if;

    -- Keep limits, XP and base score in sync with js/game.js.
    v_max_moves := (array[18,17,17,16,15,15,14,13,12,12])[p_level_id];
    v_xp := (array[100,120,140,160,180,200,230,260,300,350])[p_level_id];
    v_base_score := (array[1000,1200,1400,1600,1800,2000,2300,2600,3000,3500])[p_level_id];

    if p_moves > v_max_moves then
        raise exception 'Move count exceeds the level limit';
    end if;

    if p_level_id > 1 and not exists (
        select 1 from public.campaign_progress
        where user_id = v_user_id and level_id = p_level_id - 1 and completed = true
    ) then
        raise exception 'Previous level is not completed';
    end if;

    -- Serialize repeated completions for this player/level.
    perform pg_advisory_xact_lock(hashtextextended(v_user_id::text || ':' || p_level_id::text, 0));

    select exists (
        select 1 from public.campaign_progress
        where user_id = v_user_id and level_id = p_level_id and completed = true
    ) into v_first_completion;
    v_first_completion := not v_first_completion;
    v_xp_awarded := case when v_first_completion then v_xp else 0 end;

    if p_moves <= ceil(v_max_moves * 0.55) then
        v_stars := 3;
    elsif p_moves <= ceil(v_max_moves * 0.75) then
        v_stars := 2;
    else
        v_stars := 1;
    end if;

    v_score := greatest(0, v_base_score - p_moves * 25);

    insert into public.campaign_progress (
        user_id, level_id, completed, best_moves, best_score,
        best_stars, xp_awarded, completed_at, updated_at
    ) values (
        v_user_id, p_level_id, true, p_moves, v_score,
        v_stars, v_first_completion, now(), now()
    )
    on conflict (user_id, level_id) do update set
        completed = true,
        best_moves = case
            when public.campaign_progress.best_moves is null then excluded.best_moves
            else least(public.campaign_progress.best_moves, excluded.best_moves)
        end,
        best_score = greatest(public.campaign_progress.best_score, excluded.best_score),
        best_stars = greatest(public.campaign_progress.best_stars, excluded.best_stars),
        xp_awarded = public.campaign_progress.xp_awarded or excluded.xp_awarded,
        completed_at = coalesce(public.campaign_progress.completed_at, excluded.completed_at),
        updated_at = now();

    if v_xp_awarded > 0 then
        insert into public.player_progress (user_id, xp, updated_at)
        values (v_user_id, v_xp_awarded, now())
        on conflict (user_id) do update
        set xp = public.player_progress.xp + excluded.xp,
            updated_at = now();
    else
        insert into public.player_progress (user_id)
        values (v_user_id)
        on conflict (user_id) do nothing;
    end if;

    select best_stars into v_best_stars
    from public.campaign_progress
    where user_id = v_user_id and level_id = p_level_id;

    return jsonb_build_object(
        'success', true,
        'first_completion', v_first_completion,
        'xp_awarded', v_xp_awarded,
        'score', v_score,
        'stars', v_best_stars,
        'earned_stars', v_stars
    );
end;
$$;

revoke all on function public.complete_campaign_level_with_stars(integer, integer) from public;
revoke all on function public.complete_campaign_level_with_stars(integer, integer) from anon;
grant execute on function public.complete_campaign_level_with_stars(integer, integer) to authenticated;
