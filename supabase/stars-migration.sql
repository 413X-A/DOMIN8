-- Ensure each new Auth user receives the rows the app expects.
create or replace function public.handle_new_filler_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_username text;
begin
    v_username := coalesce(
        nullif(new.raw_user_meta_data ->> 'username', ''),
        nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
        'Player'
    );

    insert into public.profiles (id, username, display_name)
    values (new.id, v_username, v_username)
    on conflict (id) do nothing;

    insert into public.player_progress (user_id)
    values (new.id)
    on conflict (user_id) do nothing;

    insert into public.game_settings (user_id)
    values (new.id)
    on conflict (user_id) do nothing;

    return new;
end;
$$;

drop trigger if exists on_auth_user_created_filler on auth.users;
create trigger on_auth_user_created_filler
after insert on auth.users
for each row execute procedure public.handle_new_filler_user();

