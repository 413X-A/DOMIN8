-- Reset existing policies on these app tables so older permissive policies
-- cannot accidentally override the intended access rules (policies are OR-combined).
do $$
declare
    pol record;
begin
    for pol in
        select schemaname, tablename, policyname
        from pg_policies
        where schemaname = 'public'
          and tablename in ('profiles', 'player_progress', 'game_settings', 'campaign_progress')
    loop
        execute format('drop policy if exists %I on %I.%I',
            pol.policyname, pol.schemaname, pol.tablename);
    end loop;
end;
$$;

